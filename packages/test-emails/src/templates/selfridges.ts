import { dateLong, digits, fullAmount, subtotal, total } from "../format.ts";
import { html, toHtmlString } from "../html.ts";
import type { OrderItemData, Template } from "../types.ts";

// Modelled on a Selfridges order confirmation: yellow header, ITEM/DETAILS/PRICE table with
// brand and colour in caps, "£1,250.00" prices, line totals for qty > 1, "14 September 2026".

const gbp = (n: number) => `£${fullAmount(n)}`;

function itemRow(item: OrderItemData, index: number) {
  const border = index === 0 ? "" : "border-top:1px solid #ddd;";
  const lineTotal =
    item.quantity > 1
      ? html`<br /><span style="color:#666;font-size:11px"
            >${gbp(item.price * item.quantity)} total</span
          >`
      : null;
  return html` <tr>
    <td style="padding:12px 0;${border}" width="140">
      <img src="${item.imageUrl}" alt="" width="130" height="173" />
    </td>
    <td style="padding:12px;${border}" valign="top">
      <span style="font-weight:bold">${item.brand.toUpperCase()}</span><br />
      ${item.name}<br />
      <span style="color:#666">Colour: ${item.colour.toUpperCase()}</span><br />
      <span style="color:#666">Size: ${item.size}</span><br />
      <span style="color:#666">Qty: ${item.quantity}</span>
    </td>
    <td style="padding:12px 0;${border}" valign="top" align="right">
      ${gbp(item.price)}${lineTotal}
    </td>
  </tr>`;
}

