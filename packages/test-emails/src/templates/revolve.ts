import { dateUs, digits, fullAmount, subtotal, total } from "../format.ts";
import { html, toHtmlString } from "../html.ts";
import type { OrderItemData, Template } from "../types.ts";

// Modelled on a REVOLVE order confirmation: serif headline, image + details per row with
// "Color:" (US spelling), sale items shown as a struck-through price next to the red sale
// price, MM/DD/YYYY dates, tax added on top.

const usd = (n: number) => `$${fullAmount(n)}`;

function priceCell(item: OrderItemData) {
  if (item.originalPrice !== undefined && item.originalPrice > item.price) {
    return html`<span style="text-decoration:line-through;color:#999"
        >${usd(item.originalPrice)}</span
      >
      <span style="font-weight:bold;color:#c00">${usd(item.price)}</span>`;
  }
  return html`<span style="font-weight:bold">${usd(item.price)}</span>`;
}

function itemRow(item: OrderItemData, index: number) {
  const border = index === 0 ? "" : "border-top:1px solid #e1e1e1;";
  return html` <tr>
    <td width="150" style="padding:10px 0;${border}">
      <a href="https://www.revolve.com/"
        ><img src="${item.imageUrl}" alt="${item.brand} ${item.name} in ${item.colour}" width="140"
      /></a>
    </td>
    <td style="padding:10px 16px;${border}" valign="top">
      <b>${item.brand}</b><br />
      ${item.name}<br />
      Color: ${item.colour}<br />
      Size: ${item.size}<br />
      Qty: ${item.quantity}<br />
      ${priceCell(item)}
    </td>
  </tr>`;
}

