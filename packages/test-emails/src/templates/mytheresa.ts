import { compactAmount, dateDotted, digits, subtotal, total } from "../format.ts";
import { html, raw, toHtmlString } from "../html.ts";
import type { OrderItemData, Template } from "../types.ts";

// Modelled on a Mytheresa order confirmation: centred logo, "Your items" table with designer in
// caps above the product name, "€ 3,900" prices, DD.MM.YYYY dates, totals incl. VAT.

const euro = (n: number) => raw(`€&nbsp;${compactAmount(n)}`);

function itemRow(item: OrderItemData, index: number) {
  const border = index === 0 ? "" : "border-top:1px solid #e5e5e5;";
  return html` <tr>
    <td width="120" valign="top" style="padding:16px 0;${border}">
      <a href="https://www.mytheresa.com/int/en/women"
        ><img src="${item.imageUrl}" alt="${item.brand} ${item.name}" width="110"
      /></a>
    </td>
    <td valign="top" style="padding:16px;${border}">
      <p style="margin:0;font-weight:bold;text-transform:uppercase">${item.brand}</p>
      <p style="margin:4px 0">${item.name}</p>
      <p style="margin:4px 0" class="label">Colour: ${item.colour}</p>
      <p style="margin:4px 0" class="label">Size: ${item.size}</p>
      <p style="margin:4px 0" class="label">Quantity: ${item.quantity}</p>
    </td>
    <td valign="top" align="right" style="padding:16px 0;${border}">${euro(item.price)}</td>
  </tr>`;
}

